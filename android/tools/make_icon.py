"""Generates the app's adaptive launcher icon (Phase 3G) from one shape definition:

  android/app/src/main/res/drawable/ic_launcher_foreground.xml   the wrench, its glow, the HUD reticle and traces
  android/app/src/main/res/drawable/ic_launcher_background.xml   deep blue-black field with a faint teal grid
  android/app/src/main/res/drawable/ic_launcher_monochrome.xml   one-colour version for themed icons (Android 13+)
  android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml (and ic_launcher_round.xml)
  docs/android-audit/phase3g/icon/*.svg                            the same layers as SVG, for previews

Original artwork made for this project: a plain open-end wrench over a targeting reticle. It uses no game asset, logo or
lettering. 108 x 108 units (Android's adaptive icon canvas, 1 unit = 1 dp); everything that matters stays inside the
66-unit safe circle.

    python android/tools/make_icon.py          (no dependencies)
"""
import math
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")
DOCS = os.path.join(ROOT, "docs", "android-audit", "phase3g", "icon")

TEAL = "#19D3C5"        # the accent (blue-green)
TEAL_LIGHT = "#7FFFE9"
STEEL_HI = "#E6FFFB"    # wrench, head end
STEEL_LO = "#58CFC3"    # wrench, handle end
EDGE = "#03161A"        # wrench outline: keeps it apart from the reticle
BG_IN, BG_MID, BG_OUT = "#0C2D33", "#05141A", "#010608"

C = 54.0                # centre of the canvas
f = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")


def wrench_path(dy=1.3):
    """An open-end wrench, upright (jaw at the top), centred on the canvas; rotated and scaled by its group."""
    hx, hy, hr = C, 30 + dy, 14.0          # head
    sw, sr = 5.0, 5.0                      # jaw slot half-width, rounded bottom
    tip = hy - math.sqrt(hr * hr - sw * sw)
    nk = 6.0                               # neck half-width where it leaves the head
    ny = hy + math.sqrt(hr * hr - nk * nk)
    hw, top, end = 4.5, 50 + dy, 84 + dy   # handle half-width, its top and the centre of its rounded end
    p = [f"M{f(hx - sw)},{f(tip)}",
         f"A{f(hr)},{f(hr)} 0 0,0 {f(hx - nk)},{f(ny)}",
         f"L{f(hx - hw)},{f(top)}", f"L{f(hx - hw)},{f(end)}",
         f"A{f(hw)},{f(hw)} 0 0,0 {f(hx + hw)},{f(end)}",
         f"L{f(hx + hw)},{f(top)}", f"L{f(hx + nk)},{f(ny)}",
         f"A{f(hr)},{f(hr)} 0 0,0 {f(hx + sw)},{f(tip)}",
         f"L{f(hx + sw)},{f(hy)}",
         f"A{f(sr)},{f(sr)} 0 0,1 {f(hx - sw)},{f(hy)}", "Z"]
    hole = f"M{f(C)},{f(end - 4.2)} m-2,0 a2,2 0 1,0 4,0 a2,2 0 1,0 -4,0 Z"   # hanging hole near the end
    return " ".join(p) + " " + hole


def arc(r, a0, a1):
    """An open arc of radius r from angle a0 to a1 (degrees, screen: 0 = right, clockwise)."""
    x0, y0 = C + r * math.cos(math.radians(a0)), C + r * math.sin(math.radians(a0))
    x1, y1 = C + r * math.cos(math.radians(a1)), C + r * math.sin(math.radians(a1))
    large = 1 if (a1 - a0) % 360 > 180 else 0
    return f"M{f(x0)},{f(y0)} A{f(r)},{f(r)} 0 {large},1 {f(x1)},{f(y1)}"


def radial(r0, r1, a):
    c, s = math.cos(math.radians(a)), math.sin(math.radians(a))
    return f"M{f(C + r0 * c)},{f(C + r0 * s)} L{f(C + r1 * c)},{f(C + r1 * s)}"


def dot(x, y, r):
    return f"M{f(x - r)},{f(y)} a{f(r)},{f(r)} 0 1,0 {f(2 * r)},0 a{f(r)},{f(r)} 0 1,0 {f(-2 * r)},0 Z"


# The reticle: two brackets on the diagonal the wrench does not use (the wrench runs top-right to bottom-left)
R = 30.5
BRACKETS = [arc(R, -22, 112), arc(R, 158, 292)]
BRACKET_ENDS = [radial(R - 3, R + 1.2, a) for a in (-22, 112, 158, 292)]
TICKS = [radial(R - 6.5, R - 3.2, a) for a in (45, 225)] + [radial(R + 1.2, R + 2.4, a) for a in (0, 90, 180, 270)]
INNER = arc(24.0, 160, 290) + " " + arc(24.0, -20, 110)
# Two circuit traces, in the free quadrants, ending in a node
TRACES = ["M25.4,43.6 L31.6,43.6 L35.6,39.6", "M82.6,64.4 L76.4,64.4 L72.4,68.4"]
NODES = [dot(35.6, 39.6, 1.5), dot(72.4, 68.4, 1.5)]
WRENCH = wrench_path()
WRENCH_GROUP = dict(rotation=45, scale=0.86)       # head to the top right; tip and end within the safe circle


# ---------------------------------------------------------------- VectorDrawable
def vd(layers, gradient_ns=False):
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if gradient_ns else ""
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by android/tools/make_icon.py (Phase 3G). Original artwork. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            + "".join(layers) + "</vector>\n")


def vd_stroke(d, color, width, alpha=1.0, indent="    "):
    a = f' android:strokeAlpha="{f(alpha)}"' if alpha < 1 else ""
    return (f'{indent}<path android:pathData="{d}" android:strokeColor="{color}" android:strokeWidth="{f(width)}"{a}\n'
            f'{indent}    android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>\n')


def vd_fill(d, color, alpha=1.0, indent="    ", evenodd=False):
    a = f' android:fillAlpha="{f(alpha)}"' if alpha < 1 else ""
    e = ' android:fillType="evenOdd"' if evenodd else ""
    return f'{indent}<path android:pathData="{d}" android:fillColor="{color}"{a}{e}/>\n'


def vd_group(body):
    g = WRENCH_GROUP
    return (f'    <group android:pivotX="{f(C)}" android:pivotY="{f(C)}" android:rotation="{g["rotation"]}"'
            f' android:scaleX="{g["scale"]}" android:scaleY="{g["scale"]}">\n' + body + "    </group>\n")


def foreground_vd():
    hud = "".join(vd_stroke(d, TEAL, 2.0) for d in BRACKETS) + "".join(vd_stroke(d, TEAL, 1.4) for d in BRACKET_ENDS)
    hud += "".join(vd_stroke(d, TEAL_LIGHT, 1.1, .8) for d in TICKS) + vd_stroke(INNER, TEAL, .7, .45)
    hud += "".join(vd_stroke(d, TEAL, 1.0, .85) for d in TRACES) + "".join(vd_fill(d, TEAL_LIGHT) for d in NODES)
    glow = vd_stroke(WRENCH, TEAL, 9, .12, "        ") + vd_stroke(WRENCH, TEAL, 5, .22, "        ")
    body = (f'        <path android:pathData="{WRENCH}" android:fillType="evenOdd"\n'
            f'            android:strokeColor="{EDGE}" android:strokeWidth="1.4" android:strokeLineJoin="round">\n'
            '            <aapt:attr name="android:fillColor">\n'
            f'                <gradient android:type="linear" android:startX="54" android:startY="17" android:endX="54" android:endY="90"\n'
            f'                    android:startColor="{STEEL_HI}" android:centerColor="#A6F2E8" android:endColor="{STEEL_LO}"/>\n'
            '            </aapt:attr>\n        </path>\n')
    shine = vd_stroke("M52,52.3 L52,82.3", "#FFFFFF", .9, .45, "        ")   # a highlight along the handle
    return vd([hud, vd_group(glow + body + shine)], gradient_ns=True)


def grid_lines():
    return " ".join([f"M{v},0 L{v},108 M0,{v} L108,{v}" for v in range(9, 108, 9)])


def background_vd():
    bg = ('    <path android:pathData="M0,0 L108,0 L108,108 L0,108 Z">\n'
          '        <aapt:attr name="android:fillColor">\n'
          f'            <gradient android:type="radial" android:centerX="54" android:centerY="48" android:gradientRadius="78">\n'
          f'                <item android:offset="0" android:color="{BG_IN}"/>\n'
          f'                <item android:offset="0.55" android:color="{BG_MID}"/>\n'
          f'                <item android:offset="1" android:color="{BG_OUT}"/>\n'
          '            </gradient>\n        </aapt:attr>\n    </path>\n')
    return vd([bg, vd_stroke(grid_lines(), TEAL, .35, .10)], gradient_ns=True)


def monochrome_vd():
    w = "#FFFFFFFF"
    hud = "".join(vd_stroke(d, w, 2.4) for d in BRACKETS) + "".join(vd_stroke(d, w, 1.6) for d in BRACKET_ENDS)
    hud += "".join(vd_stroke(d, w, 1.3) for d in TICKS) + "".join(vd_stroke(d, w, 1.2) for d in TRACES)
    hud += "".join(vd_fill(d, w) for d in NODES)
    return vd([hud, vd_group(vd_fill(WRENCH, w, indent="        ", evenodd=True))])


ADAPTIVE = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Phase 3G launcher icon: android/tools/make_icon.py -->\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background"/>\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
            '</adaptive-icon>\n')


# ---------------------------------------------------------------- SVG (previews only)
def svg_stroke(d, color, width, alpha=1.0):
    return (f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{f(width)}" stroke-opacity="{f(alpha)}" '
            'stroke-linecap="round" stroke-linejoin="round"/>')


def svg_group(body):
    g = WRENCH_GROUP
    return f'<g transform="translate({f(C)} {f(C)}) rotate({g["rotation"]}) scale({g["scale"]}) translate({f(-C)} {f(-C)})">{body}</g>'


def svg_layers(mono=False):
    """(background, foreground) as SVG fragments in 108-unit coordinates."""
    if mono:
        w = "#FFFFFF"
        hud = "".join(svg_stroke(d, w, 2.4) for d in BRACKETS) + "".join(svg_stroke(d, w, 1.6) for d in BRACKET_ENDS)
        hud += "".join(svg_stroke(d, w, 1.3) for d in TICKS) + "".join(svg_stroke(d, w, 1.2) for d in TRACES)
        hud += "".join(f'<path d="{d}" fill="{w}"/>' for d in NODES)
        return "", hud + svg_group(f'<path d="{WRENCH}" fill="{w}" fill-rule="evenodd"/>')
    bg = ('<defs><radialGradient id="bg" cx="54" cy="48" r="78" gradientUnits="userSpaceOnUse">'
          f'<stop offset="0" stop-color="{BG_IN}"/><stop offset=".55" stop-color="{BG_MID}"/><stop offset="1" stop-color="{BG_OUT}"/>'
          '</radialGradient><linearGradient id="steel" x1="54" y1="17" x2="54" y2="90" gradientUnits="userSpaceOnUse">'
          f'<stop offset="0" stop-color="{STEEL_HI}"/><stop offset=".5" stop-color="#A6F2E8"/><stop offset="1" stop-color="{STEEL_LO}"/>'
          '</linearGradient></defs>'
          '<rect width="108" height="108" fill="url(#bg)"/>' + svg_stroke(grid_lines(), TEAL, .35, .10))
    hud = "".join(svg_stroke(d, TEAL, 2.0) for d in BRACKETS) + "".join(svg_stroke(d, TEAL, 1.4) for d in BRACKET_ENDS)
    hud += "".join(svg_stroke(d, TEAL_LIGHT, 1.1, .8) for d in TICKS) + svg_stroke(INNER, TEAL, .7, .45)
    hud += "".join(svg_stroke(d, TEAL, 1.0, .85) for d in TRACES) + "".join(f'<path d="{d}" fill="{TEAL_LIGHT}"/>' for d in NODES)
    body = (svg_stroke(WRENCH, TEAL, 9, .12) + svg_stroke(WRENCH, TEAL, 5, .22)
            + f'<path d="{WRENCH}" fill="url(#steel)" fill-rule="evenodd" stroke="{EDGE}" stroke-width="1.4" stroke-linejoin="round"/>'
            + svg_stroke("M52,52.3 L52,82.3", "#FFFFFF", .9, .45))
    return bg, hud + svg_group(body)


def svg_doc(inner, size=108):
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">{inner}</svg>\n'


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(path, ROOT))


def main():
    write(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), foreground_vd())
    write(os.path.join(RES, "drawable", "ic_launcher_background.xml"), background_vd())
    write(os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"), monochrome_vd())
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher.xml"), ADAPTIVE)
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher_round.xml"), ADAPTIVE)
    bg, fg = svg_layers()
    _, mono = svg_layers(mono=True)
    write(os.path.join(DOCS, "icon_full.svg"), svg_doc(bg + fg, 432))
    write(os.path.join(DOCS, "icon_foreground.svg"), svg_doc(fg, 432))
    write(os.path.join(DOCS, "icon_monochrome.svg"), svg_doc(mono, 432))


if __name__ == "__main__":
    main()
